results = {}
failed = []

for i, addr in enumerate(ADDRESSES):
    try:
        resp = requests.get(
            "https://restapi.amap.com/v3/geocode/geo",
            params={"key": KEY, "address": addr, "city": "哈尔滨"},
            timeout=5
        )
        data = resp.json()
        if data.get("status") == "1" and data.get("geocodes") and len(data["geocodes"]) > 0:
            loc = data["geocodes"][0]["location"]
            lng, lat = loc.split(",")
            results[addr] = {"lng": float(lng), "lat": float(lat)}
        else:
            failed.append(addr)
            results[addr] = None
    except Exception as e:
        failed.append(addr)
        results[addr] = None
        print(f"  [{i+1}/{len(ADDRESSES)}] ERROR: {addr[:30]}... - {e}")

    if (i + 1) % 20 == 0:
        print(f"  [{i+1}/{len(ADDRESSES)}] 进度... (成功 {len([v for v in results.values() if v])})")

    time.sleep(0.05)  # 控制QPS

success = len([v for v in results.values() if v])
