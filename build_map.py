def build_sidebar_html():
    """Generate static sidebar HTML with sequential IDs matching JS routeLayers."""
    groups = [('tq-body', tq), ('jb-body', jb), ('hq-body', hq)]
    html_parts = []
    global_idx = 0  # matches JS: id='r_'+allRoutes.length
    for div_id, routes in groups:
        rows = []
        for r in routes:
            name, color, stops = r
            valid = any(c(s[0]) for s in stops)
            if not valid:
                continue
            rid = 'r_%d' % global_idx
            global_idx += 1
            rows.append(
                '<div class="route-row" data-rid="%s" onclick="rowToggle(this)">'
                '<input type="checkbox" checked onclick="event.stopPropagation();rowCheck(this)">'
                '<span class="route-dot" style="background:%s"></span>'
                '<span class="route-label">%s</span>'
                '<button class="solo-btn" onclick="event.stopPropagation();rowSolo(this)" title="只看这条">👁</button>'
                '</div>' % (rid, color, name)
            )
        html_parts.append(''.join(rows))
    return tuple(html_parts)


def build_js(defs):
    lines = []
    for d in defs:
        name, color, stops = d
        js_stops = []
        for s in stops:
            sname, addr, time = s
            coord = c(sname)  # V2: look up by stop name
            if coord:
                js_stops.append('["%s",%s,%s,"%s"]' % (sname, coord[0], coord[1], time))
        if js_stops:
            lines.append('  ["%s","%s",[%s]]' % (name, color, ",".join(js_stops)))
    return "[\n" + ",\n".join(lines) + "\n]"


